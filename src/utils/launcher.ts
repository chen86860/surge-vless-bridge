import { readFile, rm } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { join } from 'node:path';
import { promisify } from 'node:util';

const execFileAsync = promisify(execFile);

export const SHARED_CONFIG_FILE_NAME = 'sing-box.json';
export const LAUNCHER_FILE_NAME = 'launcher.sh';
export const RUN_DIR_NAME = 'run';

// Surge starts one external process per node, and a url-test group starts every node at once. Running
// sing-box directly would cost one ~45 MB process per node; this script costs ~2.5 MB per node and all
// copies share a single sing-box that serves every node's port:
//
// - the first copy starts sing-box, later copies reuse it, and the last one to exit stops it;
// - every 5s each copy restarts sing-box if it died or `sing-box.json` changed since it was started,
//   so a sync takes effect even before Surge reloads;
// - `sing-box check` runs before every start, and its output lands in run/sing-box.log;
// - a copy exits on its own once Surge is gone or `clean` removed the config.
//
// A pid file alone is not trusted: macOS reuses pids, so the process must still be running this
// directory's config (or this launcher) before it is reused or killed.
export const LAUNCHER_SCRIPT = `#!/bin/sh
# Generated by surge-vless-bridge and rewritten on every sync; do not edit.
# Usage: launcher.sh <sing-box binary>
# The run directory holds sing-box's log, which can name node servers; keep it private like the rest.
umask 077
SING_BOX="$1"
DIR=$(cd "$(dirname "$0")" && pwd)
CONFIG="$DIR/${SHARED_CONFIG_FILE_NAME}"
RUN="$DIR/${RUN_DIR_NAME}"
PIDFILE="$RUN/sing-box.pid"
HASHFILE="$RUN/sing-box.hash"
LOCK="$RUN/lock"
LEASES="$RUN/leases"
mkdir -p "$LEASES"
: > "$LEASES/$$"

lock() {
  tries=0
  # \`clean\` deletes the run directory under live copies; without it mkdir would fail forever.
  until mkdir -p "$RUN" && mkdir "$LOCK" 2>/dev/null; do
    tries=$((tries + 1))
    # A copy killed while holding the lock would block every other one; no holder needs 5s.
    if [ "$tries" -ge 50 ]; then rmdir "$LOCK" 2>/dev/null; tries=0; fi
    sleep 0.1
  done
}

unlock() { rmdir "$LOCK" 2>/dev/null; }

singbox_pid() {
  pid=$(cat "$PIDFILE" 2>/dev/null) || return 1
  case $(ps -p "$pid" -o command= 2>/dev/null) in
    *"$CONFIG"*) echo "$pid" ;;
    *) return 1 ;;
  esac
}

stop_singbox() {
  if pid=$(singbox_pid); then
    kill "$pid" 2>/dev/null
    n=0
    while kill -0 "$pid" 2>/dev/null && [ "$n" -lt 30 ]; do sleep 0.1; n=$((n + 1)); done
    kill -9 "$pid" 2>/dev/null
  fi
  rm -f "$PIDFILE" "$HASHFILE"
}

ensure_singbox() {
  hash=$(cksum < "$CONFIG") || return 1
  lock
  if singbox_pid >/dev/null && [ "$(cat "$HASHFILE" 2>/dev/null)" = "$hash" ]; then
    unlock
    return 0
  fi
  stop_singbox
  if ! "$SING_BOX" check -c "$CONFIG" > "$RUN/sing-box.log" 2>&1; then
    unlock
    return 1
  fi
  "$SING_BOX" run -c "$CONFIG" >> "$RUN/sing-box.log" 2>&1 &
  echo "$!" > "$PIDFILE"
  echo "$hash" > "$HASHFILE"
  unlock
}

release() {
  trap '' TERM INT HUP
  [ -n "$sleeper" ] && kill "$sleeper" 2>/dev/null
  rm -f "$LEASES/$$"
  lock
  others=0
  for lease in "$LEASES"/*; do
    [ -e "$lease" ] || continue
    case $(ps -p "\${lease##*/}" -o command= 2>/dev/null) in
      *"$DIR/${LAUNCHER_FILE_NAME}"*) others=1 ;;
      *) rm -f "$lease" ;;
    esac
  done
  [ "$others" -eq 0 ] && stop_singbox
  unlock
  [ -f "$CONFIG" ] || rmdir "$LEASES" "$RUN" 2>/dev/null
  exit 0
}
trap release TERM INT HUP

ensure_singbox || { rm -f "$LEASES/$$"; exit 1; }
while :; do
  sleep 5 &
  sleeper=$!
  wait "$sleeper"
  # Reparented to launchd means Surge is gone; a missing config means \`clean\` ran. Either way nothing
  # will ever use this copy again, and Surge is not around to stop it.
  if [ "$(ps -o ppid= -p $$ | tr -d ' ')" = 1 ] || [ ! -f "$CONFIG" ]; then release; fi
  ensure_singbox
done
`;

const readSharedSingBoxPid = async (outputDir: string) => {
  const pid = Number((await readFile(join(outputDir, RUN_DIR_NAME, 'sing-box.pid'), 'utf8').catch(() => '')).trim());
  if (!Number.isInteger(pid) || pid <= 0) {
    return undefined;
  }

  const { stdout } = await execFileAsync('ps', ['-p', String(pid), '-o', 'command=']).catch(() => ({ stdout: '' }));
  return stdout.includes(join(outputDir, SHARED_CONFIG_FILE_NAME)) ? pid : undefined;
};

export const isSharedSingBoxRunning = async (outputDir: string) => (await readSharedSingBoxPid(outputDir)) !== undefined;

// `clean` deletes the pid file the launchers rely on, so it has to stop sing-box itself first or the
// process would outlive every launcher.
export const stopSharedSingBox = async (outputDir: string) => {
  const pid = await readSharedSingBoxPid(outputDir);
  if (pid !== undefined) {
    try {
      process.kill(pid, 'SIGTERM');
    } catch {
      // Already gone.
    }
  }

  await rm(join(outputDir, RUN_DIR_NAME), { recursive: true, force: true });
  return pid !== undefined;
};
